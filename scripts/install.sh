#!/bin/sh
# Install a verified Flik release without Rust. No sudo, shell profile edits or telemetry.
set -eu

fail() { printf 'flik: %s\n' "$*" >&2; exit 1; }
repo=${FLIK_REPO:-}
case "$repo" in
  */*) owner=${repo%%/*}; name=${repo#*/} ;;
  *) fail 'Set FLIK_REPO=OWNER/REPO to the official Flik GitHub repository.' ;;
esac
case "$owner" in ''|*[!A-Za-z0-9_.-]*) fail 'Invalid GitHub owner in FLIK_REPO.' ;; esac
case "$name" in ''|*[!A-Za-z0-9_.-]*) fail 'Invalid GitHub repository name in FLIK_REPO.' ;; esac
case "$name" in */*) fail 'FLIK_REPO must have exactly one slash.' ;; esac

for dependency in curl tar uname mktemp chmod mv; do
  command -v "$dependency" >/dev/null 2>&1 || fail "Missing required command: $dependency"
done
if command -v sha256sum >/dev/null 2>&1; then
  hash_command=sha256sum
elif command -v shasum >/dev/null 2>&1; then
  hash_command=shasum
else
  fail 'Install sha256sum or shasum to verify the download.'
fi
case "$(uname -s):$(uname -m)" in
  Linux:x86_64|Linux:amd64) target=x86_64-unknown-linux-musl ;;
  Linux:aarch64|Linux:arm64) target=aarch64-unknown-linux-musl ;;
  Darwin:x86_64) target=x86_64-apple-darwin ;;
  Darwin:arm64) target=aarch64-apple-darwin ;;
  *) fail 'Supported release platforms: Linux x86-64/ARM64 and macOS Intel/Apple Silicon.' ;;
esac

fetch() {
  curl --proto '=https' --tlsv1.2 --fail --location --silent --show-error \
    --retry 3 --connect-timeout 15 --max-time 120 "$@"
}
version=${FLIK_VERSION:-latest}
if [ "$version" = latest ]; then
  resolved=$(fetch --head --output /dev/null --write-out '%{url_effective}' "https://github.com/$repo/releases/latest") || fail 'Cannot resolve the latest published release.'
  case "$resolved" in
    "https://github.com/$repo/releases/tag/"*) version=${resolved##*/} ;;
    *) fail 'GitHub did not return a published release URL for this repository.' ;;
  esac
fi
case "$version" in v*) ;; *) version=v$version ;; esac
# Only stable version tags generated by the release workflow are accepted.
printf '%s\n' "$version" | LC_ALL=C grep -Eq '^v[0-9]+\.[0-9]+\.[0-9]+$' || fail 'FLIK_VERSION must be latest or vMAJOR.MINOR.PATCH.'

install_dir=${FLIK_INSTALL_DIR:-${HOME:?HOME is required}/.local/bin}
case "$install_dir" in /*) ;; *) fail 'FLIK_INSTALL_DIR must be an absolute path.' ;; esac
case ${FLIK_FORCE:-0} in 0|1) ;; *) fail 'FLIK_FORCE must be 0 or 1.' ;; esac
if [ -L "$install_dir/flik" ] || [ -L "$install_dir/flik.LICENSE" ]; then fail 'Refusing to replace a symbolic link named flik or flik.LICENSE.'; fi
if [ -e "$install_dir/flik" ] && [ "${FLIK_FORCE:-0}" != 1 ]; then
  fail 'flik already exists there. Set FLIK_FORCE=1 to replace it, or choose another FLIK_INSTALL_DIR.'
fi
if [ -e "$install_dir/flik" ] && [ ! -f "$install_dir/flik" ]; then fail 'Destination flik is not a regular file.'; fi
if [ -e "$install_dir/flik.LICENSE" ]; then
  [ -f "$install_dir/flik.LICENSE" ] || fail 'Destination flik.LICENSE is not a regular file.'
  [ "${FLIK_FORCE:-0}" = 1 ] || fail 'flik.LICENSE already exists there; use FLIK_FORCE=1 for an intentional update.'
fi

umask 077
task_tmp=$(mktemp -d "${TMPDIR:-/tmp}/flik-install.XXXXXX") || fail 'Cannot create a temporary directory.'
stage=
stage_license=
cleanup() {
  rm -rf "$task_tmp"
  if [ -n "$stage" ]; then rm -f "$stage"; fi
  if [ -n "$stage_license" ]; then rm -f "$stage_license"; fi
}
trap cleanup EXIT
trap 'exit 1' HUP INT TERM
archive=flik-$version-$target.tar.gz
base=https://github.com/$repo/releases/download/$version
printf 'Downloading Flik %s (%s)…\n' "$version" "$target"
fetch --output "$task_tmp/$archive" "$base/$archive" || fail 'Binary download failed. Check that this release and platform asset are published.'
fetch --output "$task_tmp/SHA256SUMS" "$base/SHA256SUMS" || fail 'Checksum download failed.'
expected=$(awk -v file="$archive" '$2 == file { if (++n > 1) exit 1; value=$1 } END { if (n != 1) exit 1; print value }' "$task_tmp/SHA256SUMS") || fail 'Missing or duplicate checksum entry.'
printf '%s\n' "$expected" | LC_ALL=C grep -Eq '^[0-9a-fA-F]{64}$' || fail 'Malformed SHA-256 checksum.'
if [ "$hash_command" = sha256sum ]; then
  actual=$(sha256sum "$task_tmp/$archive")
else
  actual=$(shasum -a 256 "$task_tmp/$archive")
fi
actual=${actual%% *}
[ "$(printf '%s' "$actual" | tr A-F a-f)" = "$(printf '%s' "$expected" | tr A-F a-f)" ] || fail 'SHA-256 mismatch; nothing was installed.'
listing=$(tar -tzf "$task_tmp/$archive") || fail 'Cannot read the archive.'
printf '%s\n' "$listing" | awk '
  $0 == "flik" { binary++; next }
  $0 == "LICENSE" { license++; next }
  { bad=1 }
  END { if (binary != 1 || license != 1 || bad) exit 1 }
' || fail 'Archive must contain only flik and LICENSE.'
# Extract to stdout so archive paths and permissions cannot write arbitrary files.
tar -xOzf "$task_tmp/$archive" flik > "$task_tmp/flik" || fail 'Cannot extract the binary.'
[ -s "$task_tmp/flik" ] || fail 'The archive does not contain a regular binary.'
tar -xOzf "$task_tmp/$archive" LICENSE > "$task_tmp/LICENSE" || fail 'Cannot extract the license.'
[ -s "$task_tmp/LICENSE" ] || fail 'The release license is empty.'
chmod 755 "$task_tmp/flik"
output=$("$task_tmp/flik" --version) || fail 'Verified binary could not run. On macOS, check the operating system security message; this release is not notarized.'
[ "$output" = "flik ${version#v}" ] || fail 'Binary version does not match its release tag.'
mkdir -p "$install_dir" || fail 'Cannot create the installation directory.'
stage=$(mktemp "$install_dir/.flik.XXXXXX") || fail 'Cannot stage the binary in the installation directory.'
cat "$task_tmp/flik" > "$stage"
chmod 755 "$stage"
stage_license=$(mktemp "$install_dir/.flik-license.XXXXXX") || fail 'Cannot stage the license.'
cat "$task_tmp/LICENSE" > "$stage_license"
chmod 644 "$stage_license"
if [ "${FLIK_FORCE:-0}" = 1 ]; then
  mv -f "$stage_license" "$install_dir/flik.LICENSE"
  mv -f "$stage" "$install_dir/flik"
else
  mv -n "$stage_license" "$install_dir/flik.LICENSE"
  [ ! -f "$stage_license" ] || fail 'License destination appeared during installation; nothing was replaced.'
  mv -n "$stage" "$install_dir/flik"
  [ ! -f "$stage" ] || fail 'Destination appeared during installation; executable was not replaced.'
fi
stage=
stage_license=
printf 'Installed %s to %s/flik\n' "$output" "$install_dir"
case ":${PATH:-}:" in
  *":$install_dir:"*) printf 'Run: flik /path/to/app.log\n' ;;
  *) printf 'Add this directory to PATH: %s\nOr run: %s/flik /path/to/app.log\n' "$install_dir" "$install_dir" ;;
esac
